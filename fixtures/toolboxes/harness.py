def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")


def tree_snapshot(root):
    """File bytes and link targets, without following links or hashing timestamps."""
    root = Path(root)
    if not root.is_dir() or root.is_symlink():
        raise ValueError("snapshot root must be a real directory")
    result = {}
    for directory, dirs, files in os.walk(root, followlinks=False):
        for name in sorted(dirs + files):
            path = Path(directory) / name
            relative = path.relative_to(root).as_posix()
            if path.is_symlink():
                result[relative] = {"link": os.readlink(path)}
            elif path.is_file():
                digest = hashlib.sha256()
                with path.open("rb") as source:
                    for chunk in iter(lambda: source.read(65536), b""):
                        digest.update(chunk)
                result[relative] = {"sha256": digest.hexdigest(), "bytes": path.stat().st_size}
    return result


def assert_no_secrets(blobs, values=None):
    """Scan supplied generated bytes. Failure names the sentinel, never its value."""
    values = SECRET_VALUES if values is None else values
    for label, blob in blobs.items():
        if isinstance(blob, str):
            blob = blob.encode()
        for name, value in values.items():
            if value and value.encode() in blob:
                raise AssertionError(f"{label}: resolved value for {name} leaked")


def assert_scrubbed(environment_names):
    leaked = MEMBER_SECRET_NAMES.intersection(environment_names)
    if leaked:
        raise AssertionError("member environment exposes " + ", ".join(sorted(leaked)))


def assert_pinned_tools(listings):
    """Check observed downstream catalogs; never sort observations before comparing."""
    if not listings:
        raise AssertionError("no downstream tools/list evidence")
    first = listings[0]
    names = [tool["name"] for tool in first["tools"]]
    if names != sorted(set(names)):
        raise AssertionError("downstream tools are not uniquely sorted")
    for listing in listings[1:]:
        if listing != first:
            raise AssertionError("downstream tool definitions changed")


