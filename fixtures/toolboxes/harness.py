def load_cases():
    return json.loads((HERE / "cases.json").read_text())["cases"]


class CaseLedger:
    """Record externally observed evidence. Preparing a fixture never passes a case."""

    def __init__(self):
        self.cases = {case["id"]: {"status": "not_run", "evidence": []} for case in load_cases()}

    def record(self, case, status, evidence):
        if case not in self.cases or status not in {"pass", "fail", "deferred"}:
            raise ValueError("unknown acceptance case or result status")
        if not evidence or any(not str(item).strip() for item in evidence):
            raise ValueError("acceptance results require evidence paths or an explicit limitation")
        self.cases[case] = {"status": status, "evidence": list(evidence)}

    def save(self, path):
        write_json(path, {"schema": 1, "cases": self.cases})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("self-test")
    prep = sub.add_parser("prepare")
    prep.add_argument("--out", type=Path, required=True)
    prep.add_argument("--http-url", default="http://127.0.0.1:9/mcp")
    sub.add_parser("cases")
    args = parser.parse_args()
    if args.command == "self-test":
        suite = unittest.defaultTestLoader.discover(str(HERE), pattern="self_test.py")
        return 0 if unittest.TextTestRunner(verbosity=2).run(suite).wasSuccessful() else 1
    if args.command == "prepare":
        manifest = prepare(args.out, http_url=args.http_url)
        print(json.dumps({"root": manifest["root"], "python": manifest["python"],
                          "manifest": str(args.out / "manifest.json")}))
    else:
        print(json.dumps(load_cases(), indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
