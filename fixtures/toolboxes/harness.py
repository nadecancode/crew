class RpcProcess:
    """Bounded JSON-lines client for this stub or scheduler's Rust fake-mcp."""

    def __init__(self, argv, *, env, cwd, timeout=3):
        self.timeout = timeout
        self.counter = 0
        self.pending = bytearray()
        self.process = subprocess.Popen(argv, env=env, cwd=cwd, stdin=subprocess.PIPE,
                                        stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        self.selector = selectors.DefaultSelector()
        self.selector.register(self.process.stdout, selectors.EVENT_READ)

    def send(self, request):
        self.process.stdin.write(json.dumps(request).encode() + b"\n")
        self.process.stdin.flush()

    def request(self, method, params=None, *, timeout=None):
        self.counter += 1
        identity = "fixture-" + str(self.counter)
        self.send({"jsonrpc": "2.0", "id": identity, "method": method, "params": params or {}})
        deadline = time.monotonic() + (self.timeout if timeout is None else timeout)
        while True:
            if time.monotonic() >= deadline:
                raise TimeoutError("fixture RPC timed out: " + method)
            if b"\n" in self.pending:
                line, _, remaining = self.pending.partition(b"\n")
                self.pending = bytearray(remaining)
                reply = json.loads(line)
                if reply.get("id") == identity:
                    return reply
                continue
            remaining = deadline - time.monotonic()
            if remaining <= 0 or not self.selector.select(remaining):
                raise TimeoutError("fixture RPC timed out: " + method)
            chunk = os.read(self.process.stdout.fileno(), 65536)
            if not chunk:
                raise EOFError("fixture upstream exited during " + method)
            self.pending.extend(chunk)
            if len(self.pending) > 2 * 1024 * 1024:
                raise ValueError("fixture response exceeds 2 MiB")

    def close(self):
        if self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=2)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=2)
        self.selector.close()
        self.process.stdin.close()
        self.process.stdout.close()

    def __enter__(self):
        return self

    def __exit__(self, *_args):
        self.close()


def http_request(url, method, *, identity="fixture-http", params=None, headers=None, timeout=3):
    parsed = urlparse(url)
    if parsed.scheme != "http" or parsed.hostname != "127.0.0.1":
        raise ValueError("fixture HTTP requests must stay on 127.0.0.1")
    request = Request(url, json.dumps({"jsonrpc": "2.0", "id": identity,
                                      "method": method, "params": params or {}}).encode(),
                      headers={"Content-Type": "application/json", **(headers or {})})
    # Ignore HTTP_PROXY, HTTPS_PROXY and the operator's proxy configuration.
    class NoRedirect(HTTPRedirectHandler):
        def redirect_request(self, *_args, **_kwargs):
            return None

    with build_opener(ProxyHandler({}), NoRedirect()).open(request, timeout=timeout) as response:
        return json.load(response)


@contextmanager
def http_stub(root, *, control=None):
    root = Path(root)
    ready = root / "http-ready.json"
    ready.unlink(missing_ok=True)
    argv = [sys.executable, str(HERE / "mcp_stub.py"), "--http", "--ready-file", str(ready)]
    if control:
        argv.extend(["--control", str(control)])
    child = subprocess.Popen(argv, env=isolated_environment(root), cwd=root,
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        deadline = time.monotonic() + 3
        while not ready.exists():
            if child.poll() is not None:
                raise RuntimeError("fixture HTTP server exited before readiness")
            if time.monotonic() >= deadline:
                raise TimeoutError("fixture HTTP server did not become ready")
            time.sleep(0.01)
        yield json.loads(ready.read_text())["url"]
    finally:
        if child.poll() is None:
            child.terminate()
            try:
                child.wait(timeout=2)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait(timeout=2)


def substitute(value, replacements):
    if isinstance(value, dict):
        return {key: substitute(item, replacements) for key, item in value.items()}
    if isinstance(value, list):
        return [substitute(item, replacements) for item in value]
    if isinstance(value, str):
        for key, replacement in replacements.items():
            value = value.replace(key, replacement)
    return value


def prepare(root, *, http_url="http://127.0.0.1:9/mcp"):
    """Materialize only beneath a new output directory. Never inspect a real home."""
    root = Path(root).resolve()
    root.mkdir(mode=0o700)  # Refuse an existing path, even one from an earlier run.
    for name in ["operator-home", "project", "member", "evidence", "bin", "runtime", "secret-input"]:
        (root / name).mkdir(mode=0o700)
    (root / ".fixture-owned").write_text("toolbox-fixtures-v1\n")
    (root / "empty-config.toml").write_text("")
    for name in ["mcp_stub.py", "runtime_stub.py"]:
        shutil.copyfile(HERE / name, root / name)
    shutil.copytree(HERE / "items", root / "items")
    replacements = {"@ROOT@": str(root), "@PYTHON@": sys.executable, "@HTTP_URL@": http_url}
    for source in (HERE / "teams").glob("*.yaml"):
        write_json(root / "teams" / source.name, substitute(json.loads(source.read_text()), replacements))
    for source in (HERE / "styles").glob("*.yaml"):
        write_json(root / "styles" / source.name, substitute(json.loads(source.read_text()), replacements))
    for runtime in ["claude", "codex", "pi", "hook"]:
        argv = [sys.executable, str(root / "runtime_stub.py"), "--fixture-runtime", runtime,
                "--fixture-log", str(root / "evidence/runtime.jsonl")]
        wrapper = root / "bin" / runtime
        wrapper.write_text("#!/bin/sh\nexec " + shlex.join(argv) + ' "$@"\n')
