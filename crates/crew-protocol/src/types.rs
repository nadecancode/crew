fn short_hex(hex: &str) -> &str {
    hex.get(..12).unwrap_or(hex)
}

impl Agent {
    /// The model the agent runs on, by its proper name (`Opus 5.5`): as the
    /// daemon resolved it, else worked out from what the session reports or
    /// from the name it was given in the team.
    pub fn model_label(&self) -> Option<String> {
        self.model_name
            .clone()
            .or_else(|| {
                self.running_model
                    .as_deref()
                    .or(self.model.as_deref())
                    .map(model_display_name)
            })
            .filter(|name| !name.is_empty())
    }
}

/// A model id without what only lengthens it: the vendor prefix, a trailing
/// release date, a bracketed variant (`claude-haiku-4-5-20251001` is
/// `haiku-4-5`).
pub fn short_model(id: &str) -> String {
    let id = id.trim();
    let id = id.split('[').next().unwrap_or(id);
    // pi names a model with its provider in front: `anthropic/claude-opus-4-6`.
    let id = id.rsplit_once('/').map_or(id, |(_, name)| name);
    let id = id.strip_prefix("claude-").unwrap_or(id);
    match id.rsplit_once('-') {
        Some((name, date)) if date.len() == 8 && date.bytes().all(|b| b.is_ascii_digit()) => {
            name.to_string()
        }
        _ => id.to_string(),
    }
}

/// A model's proper name, from its id: `claude-opus-5-5` is `Opus 5.5`,
/// `gpt-6-astra` is `GPT 6 Astra`, `gpt-6.1-sol` is `GPT 6.1 Sol`.
pub fn model_display_name(id: &str) -> String {
    let mut words: Vec<String> = Vec::new();
    for part in short_model(id).split('-').filter(|p| !p.is_empty()) {
        let is_number = part.bytes().all(|b| b.is_ascii_digit());
        let version = |word: &str| word.bytes().all(|b| b.is_ascii_digit() || b == b'.');
        match words.last_mut() {
            // `5-5` is version 5.5.
            Some(last) if is_number && version(last) => {
                last.push('.');
                last.push_str(part);
            }
            _ if part.eq_ignore_ascii_case("gpt") => words.push("GPT".to_string()),
            _ if part.eq_ignore_ascii_case("glm") => words.push("GLM".to_string()),
            _ if part.eq_ignore_ascii_case("deepseek") => words.push("DeepSeek".to_string()),
            _ => {
                let mut chars = part.chars();
                let first = chars.next().map(|c| c.to_ascii_uppercase());
                words.push(first.into_iter().chain(chars).collect());
            }
        }
    }
    words.join(" ")
}

/// A message on the bus.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Message {
    pub id: String,
    pub from: String,
    /// Recipient agent id, or `*` for a broadcast.
    pub to: String,
    #[serde(rename = "type")]
    pub kind: MessageType,
    pub body: String,
    pub timestamp: i64,
    #[serde(default)]
    pub correlation_id: Option<String>,
    #[serde(default)]
    pub reply_to: Option<String>,
    #[serde(default)]
    pub metadata: Value,
}

impl Message {
    pub fn is_broadcast(&self) -> bool {
        self.to == BROADCAST
    }

    /// True for worker-to-worker traffic that bypasses the orchestrator.
    pub fn is_p2p(&self) -> bool {
        !self.is_broadcast()
            && self.from != ORCHESTRATOR_ID
            && self.to != ORCHESTRATOR_ID
            && self.from != OPERATOR_ID
            && self.to != OPERATOR_ID
    }

    /// A question an agent put to the human operator. It stays open until
    /// the operator answers it.
    pub fn is_operator_question(&self) -> bool {
        self.to == OPERATOR_ID && self.kind == MessageType::Question
    }

    /// The answers the asker suggests for an operator question.
    pub fn options(&self) -> Vec<String> {
        self.metadata
            .get("options")
            .and_then(Value::as_array)
            .map(|options| {
                options
                    .iter()
                    .filter_map(Value::as_str)
                    .map(str::to_string)
                    .collect()
            })
            .unwrap_or_default()
    }

    /// The teammate whose question the asker passes on to the operator.
    pub fn asked_by(&self) -> Option<&str> {
        self.metadata.get("asked_by").and_then(Value::as_str)
    }

    /// Who wants to know, for display: `orchestrator`, or
    /// `orchestrator, for claude-2` when it passes a member's question on.
    pub fn asker(&self) -> String {
        match self.asked_by() {
            Some(member) => format!("{}, for {member}", self.from),
            None => self.from.clone(),
        }
    }
}

