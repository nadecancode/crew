/// Token accounting for an agent session, when the runtime exposes it.
#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq, Eq)]
pub struct Usage {
    pub input_tokens: u64,
    pub output_tokens: u64,
    pub cache_read_tokens: u64,
    pub cache_creation_tokens: u64,
    pub turns: u64,
}

/// How full an agent's context window is, as its runtime last reported it.
#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq, Eq)]
pub struct ContextUsage {
    /// Tokens the last model request was answered over.
    pub tokens: u64,
    /// The model's context window, in tokens.
    pub window: u64,
    /// `tokens` over `window`, 0 to 100.
    pub percent: u8,
    pub updated_at: i64,
}

impl ContextUsage {
    pub fn new(tokens: u64, window: u64, updated_at: i64) -> Self {
        let percent = if window == 0 {
            0
        } else {
            (tokens.saturating_mul(100) / window).min(100) as u8
        };
        Self {
            tokens,
            window,
            percent,
            updated_at,
        }
    }
}

