//! Emit the one committed browser policy module from live client descriptors.
//! Web builds consume the result without running Cargo or this example.

use std::collections::HashSet;
use std::fmt::Write;

use crew_client::policy::{CommandPolicy, WebCommandKind, WebPolicy};
use crew_client::CommandKind;

const JS_MAX_SAFE_INTEGER: u64 = (1 << 53) - 1;

/// Stable emission shared by the maintainer command and stale-output test.
pub fn render(policy: WebPolicy) -> Result<String, String> {
    let fallback: Vec<_> = policy
        .method_timeouts
        .iter()
        .filter(|method| method.kind.is_none())
        .collect();
    if fallback.len() != 1 {
        return Err("exactly one ordinary timeout descriptor is required".into());
    }
    let default = fallback[0].timeout_ms;
    let mut methods = HashSet::new();
    let mut groups: Vec<(u64, Vec<&str>)> = Vec::new();
    for method in policy.method_timeouts {
        if method.timeout_ms == 0 || method.timeout_ms > JS_MAX_SAFE_INTEGER {
            return Err("timeout must be a positive exact JavaScript integer".into());
        }
        let Some(kind) = method.kind else {
            continue;
        };
        if !methods.insert(kind) {
            return Err(format!("duplicate method: {}", kind.method()));
        }
        if method.timeout_ms == default {
            continue;
        }
        if let Some((_, names)) = groups
            .iter_mut()
            .find(|(timeout, _)| *timeout == method.timeout_ms)
        {
            names.push(kind.method());
        } else {
            groups.push((method.timeout_ms, vec![kind.method()]));
        }
    }
    if methods.len() != CommandKind::ALL.len()
        || CommandKind::ALL.iter().any(|kind| !methods.contains(kind))
    {
        return Err("every application command needs exactly one descriptor".into());
    }
    let mut names = HashSet::new();
    for command in policy.commands {
        for name in std::iter::once(command.name).chain(command.aliases.iter().copied()) {
            if !valid_name(name) || !names.insert(name.to_ascii_lowercase()) {
                return Err(format!("invalid or duplicate command name/alias: {name}"));
            }
        }
    }

    let mut out = String::from(
        "// Generated by crates/crew-client/examples/generate_web_policy.rs. Do not edit.\n\n",
    );
    out.push_str("export function timeoutFor(method: string): number {\n  switch (method) {\n");
    for (timeout, names) in groups {
        for name in names {
            writeln!(out, "    case {}:", quote(name)).unwrap();
        }
        writeln!(out, "      return {timeout};").unwrap();
    }
    writeln!(out, "    default:\n      return {default};\n  }}\n}}\n").unwrap();
    out.push_str("export type GeneratedCommand = { name: string; aliases: string[]; args: string; about: string; web?: \"declined\" | \"new\" };\n");
    out.push_str(
        "type CommandTuple = [string, string, string?, string[]?, GeneratedCommand[\"web\"]?];\n\n",
    );
    out.push_str("export const COMMANDS: GeneratedCommand[] = ([\n");
    for (index, command) in policy.commands.iter().enumerate() {
        write!(out, "  {}", tuple(command)).unwrap();
        out.push_str(if index + 1 == policy.commands.len() {
            "\n"
        } else {
            ",\n"
        });
    }
    out.push_str("] as CommandTuple[]).map(([name, about, args = \"\", aliases = [], web]) => ({ name, about, args, aliases, web }));\n");
    Ok(out)
}

fn valid_name(name: &str) -> bool {
    if name == "?" {
        return true;
    }
    let mut bytes = name.bytes();
    bytes.next().is_some_and(|byte| byte.is_ascii_alphabetic())
        && bytes.all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-'))
}

fn quote(text: &str) -> String {
    serde_json::to_string(text).expect("a string always serializes")
}

fn tuple(command: &CommandPolicy) -> String {
    let mut slots = vec![quote(command.name), quote(command.about)];
    let last = if command.web.is_some() {
        4
    } else if !command.aliases.is_empty() {
        3
    } else if !command.args.is_empty() {
        2
    } else {
        1
    };
    if last >= 2 {
        slots.push(if command.args.is_empty() {
            "undefined".into()
        } else {
            quote(command.args)
        });
    }
    if last >= 3 {
        slots.push(if command.aliases.is_empty() {
            "undefined".into()
        } else {
            format!(
                "[{}]",
                command
                    .aliases
                    .iter()
                    .map(|name| quote(name))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        });
    }
    if let Some(web) = command.web {
        slots.push(quote(match web {
            WebCommandKind::Declined => "declined",
            WebCommandKind::New => "new",
        }));
    }
    format!("[{}]", slots.join(", "))
}

#[cfg(not(test))]
fn main() {
    print!(
        "{}",
        render(crew_client::policy::web_policy()).expect("valid runtime policy descriptors")
    );
}
